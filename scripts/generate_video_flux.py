#!/usr/bin/env python3
"""Generate video with FLUX 3 Video (Black Forest Labs) via the BFL API — docs.bfl.ai/flux_3/flux3_video

One endpoint, four modes, one request shape keyed by `mode`:
    POST https://api.bfl.ai/v1/flux-3-video      header  x-key: $BFL_API_KEY
    t2v            text → video                      --prompt
    i2v            images become frames (keyframes)   --image start.png [--last-frame end.png] [--keyframe 4.5:mid.png ...]
    v2v            continue a clip from its last frames --video clip.mp4   (source ≤ 15 s, ≤ 50 MB; adds 5–15 s)
    draft_enhance  full-quality re-render of a --draft result   --enhance draft.mp4  (uses the cached bundle, same seed/inputs)
Tools:
    --upscale clip.mp4   POST /v1/flux-tools/video-upscale-v1  (1.5–3×, first 20 s, source ≤ 2560×1440, ≤ 50 MB)
    --download <id>      recover a finished result by task id (no new generation)
    --credits            print the account balance

Everything is asynchronous: submit → {id, polling_url, cost} → poll until status "Ready" → download result.sample.
Local files are sent inline as base64 (no S3 / upload step needed). Result URLs expire after ~2 h — the script
downloads immediately and writes a sidecar `<output>.json` (task id, mode, params, cost in credits, draft-cache path).

Usage:
    source ~/config.env   # BFL_API_KEY

    # Image-to-video from a storyboard still (most common). Prompt = the CHANGE + camera + audio, not the subject.
    python scripts/generate_video_flux.py --prompt "Use this image as the first frame. Camera holds locked. ..." \
        --image storyboard/scene_01.png --duration 8 --output clips/scene_01.mp4

    # Draft first (~⅓ cost, fast), then enhance the keeper at full quality / fhd — same generation, no re-roll
    python scripts/generate_video_flux.py --prompt "..." --image s.png --duration 8 --draft --output drafts/s.mp4
    python scripts/generate_video_flux.py --enhance drafts/s.mp4 --resolution fhd --output clips/s.mp4

    # Text-to-video, vertical, fhd, 12 s, silent
    python scripts/generate_video_flux.py --prompt "..." --ratio 9:16 --resolution fhd --duration 12 --no-audio --output clip.mp4

    # First + last frame (morph / land on a packshot)
    python scripts/generate_video_flux.py --prompt "..." --image a.png --last-frame b.png --duration 6 --output clip.mp4

    # Middle keyframes spaced evenly by the API (needs --image, --last-frame and --duration)
    python scripts/generate_video_flux.py --prompt "..." --image a.png --mid-image b.png --mid-image c.png --last-frame d.png --duration 12 --output clip.mp4

    # Timed keyframes  seconds:file  (up to 10 images; --duration required)
    python scripts/generate_video_flux.py --prompt "a seed grows into a tree through the seasons" \
        --keyframe 0:seed.png --keyframe 4.5:sapling.png --keyframe 10:tree.png --duration 10 --output tree.mp4

    # Continue a clip (v2v)
    python scripts/generate_video_flux.py --prompt "Continue the reference video from its final frames. She ..." \
        --video clips/scene_01.mp4 --duration 8 --output clips/scene_01_ext.mp4

    # Upscale toward 4K (creativity 0 = faithful, 1 = enhance detail)
    python scripts/generate_video_flux.py --upscale clips/s.mp4 --upscale-factor 2 --creativity 0 --output clips/s_4k.mp4

Notes:
    - Duration: whole seconds 5–20 (v2v 5–15) or "auto" (default). 24 fps. hd ≈ 720p class, fhd ≈ 1080p (1920×1088 at 16:9).
    - Aspect: auto | 21:9 | 2:1 | 16:9 | 4:3 | 1:1 | 3:4 | 9:16. Match your stills to the output aspect.
    - Audio is generated by default (dialogue, ambience, effects, music) — say what you want or pass --no-audio.
    - Cost (Sept 2026, per second of output): t2v/i2v hd $0.17 · fhd $0.29 · draft $0.06 · v2v hd $0.43 · fhd $0.54 · draft $0.12.
      The API bills in credits (1 credit ≈ $0.01); the settled figure is written to the sidecar.
    - safety_tolerance 0–4 (default 2). Keep 2 for brand work.
"""
